-- V66 — 미팅 회고 (specs/meeting-retro/spec.md, ST-039)
-- STUDY_MEETING_RETRO: 회차 × 참여자 한 줄 (회차·참여자 유일).
--   MEETING_ID → STUDY_MEETING, PARTICIPANT_ID → STUDY_PARTICIPANT: 다른 애그리거트라 FK 없이 ID 참조.
-- STUDY_MEETING_RETRO_LIKE: 회고 × 문항 × 계정 한 줄. 기한과 상관없이 누르고 취소한다.
--   RETRO_ID → STUDY_MEETING_RETRO: 같은 애그리거트 — FK + CASCADE DELETE.
--   ACCOUNT_ID: 다른 애그리거트라 FK 없이 ID 참조.
-- 시각은 모두 UTC.
CREATE TABLE STUDY_MEETING_RETRO (
    ID             BIGINT       NOT NULL AUTO_INCREMENT,
    MEETING_ID     BIGINT       NOT NULL,
    PARTICIPANT_ID BIGINT       NOT NULL,
    GOOD           VARCHAR(500) NOT NULL,
    IMPROVE        VARCHAR(500) NOT NULL,
    FEELING        VARCHAR(500) NOT NULL DEFAULT '',
    CREATED_AT     DATETIME(6)  NOT NULL,
    UPDATED_AT     DATETIME(6)  NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE INDEX uk_retro_meeting_participant (MEETING_ID, PARTICIPANT_ID),
    INDEX idx_retro_meeting (MEETING_ID)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE STUDY_MEETING_RETRO_LIKE (
    ID         BIGINT      NOT NULL AUTO_INCREMENT,
    RETRO_ID   BIGINT      NOT NULL,
    SECTION    VARCHAR(16) NOT NULL,
    ACCOUNT_ID BIGINT      NOT NULL,
    CREATED_AT DATETIME(6) NOT NULL,
    UPDATED_AT DATETIME(6) NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE INDEX uk_retro_like (RETRO_ID, SECTION, ACCOUNT_ID),
    CONSTRAINT fk_retro_like_retro FOREIGN KEY (RETRO_ID) REFERENCES STUDY_MEETING_RETRO (ID) ON DELETE CASCADE,
    INDEX idx_retro_like_account (ACCOUNT_ID)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;
