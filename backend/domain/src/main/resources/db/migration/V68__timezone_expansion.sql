-- STUDY_RECRUITMENT.RECRUIT_DEADLINE_AT 은 바꾸지 않는다 — 레거시 마감은 저장된 UTC 로만 판정한다 (§4.5 A안).
-- STUDY.TIMEZONE 은 지우지 않는다. 아래 이관이 읽고 나면 앱은 더 쓰지 않는다 (읽기 전용 · 폐기 예정).

ALTER TABLE ACCOUNT ADD COLUMN ADMIN_DISPLAY_TIME_ZONE VARCHAR(64) NULL;

ALTER TABLE STUDY_RECRUITMENT ADD COLUMN RECRUITMENT_TZ_MODE VARCHAR(16) NOT NULL DEFAULT 'unset';

-- 같은 모집 회차 애그리거트 안의 자식이지만 외래키 없이 둔다(논리 FK). 회차 삭제는 앱이 자식부터 지운다
CREATE TABLE STUDY_RECRUITMENT_ZONE (
    ID                   BIGINT      NOT NULL AUTO_INCREMENT,
    STUDY_RECRUITMENT_ID BIGINT      NOT NULL,
    TIME_ZONE            VARCHAR(64) NOT NULL,
    CREATED_AT           DATETIME(6) NOT NULL,
    UPDATED_AT           DATETIME(6) NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE INDEX uk_study_recruitment_zone (STUDY_RECRUITMENT_ID, TIME_ZONE)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

-- 이관 (§4.4): 스터디별 최신(ID 최대) 모집 회차에만 옮긴다. NULL 은 unset 그대로 — 일정 문구로 추정하지 않는다.
-- 임시 테이블 · CREATE ... SELECT 는 GTID 일관성 모드에서 막혀 쓰지 않는다
INSERT INTO STUDY_RECRUITMENT_ZONE (STUDY_RECRUITMENT_ID, TIME_ZONE, CREATED_AT, UPDATED_AT)
SELECT r.ID, 'Asia/Seoul', NOW(6), NOW(6)
FROM STUDY_RECRUITMENT r
         JOIN STUDY s ON s.ID = r.STUDY_ID
WHERE r.ID = (SELECT MAX(r2.ID) FROM STUDY_RECRUITMENT r2 WHERE r2.STUDY_ID = r.STUDY_ID)
  AND UPPER(s.TIMEZONE) IN ('KST', 'BOTH');

INSERT INTO STUDY_RECRUITMENT_ZONE (STUDY_RECRUITMENT_ID, TIME_ZONE, CREATED_AT, UPDATED_AT)
SELECT r.ID, 'America/Los_Angeles', NOW(6), NOW(6)
FROM STUDY_RECRUITMENT r
         JOIN STUDY s ON s.ID = r.STUDY_ID
WHERE r.ID = (SELECT MAX(r2.ID) FROM STUDY_RECRUITMENT r2 WHERE r2.STUDY_ID = r.STUDY_ID)
  AND UPPER(s.TIMEZONE) IN ('PST', 'BOTH');

UPDATE STUDY_RECRUITMENT
SET RECRUITMENT_TZ_MODE = 'selected'
WHERE ID IN (SELECT z.STUDY_RECRUITMENT_ID FROM STUDY_RECRUITMENT_ZONE z);
