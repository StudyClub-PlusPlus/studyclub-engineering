CREATE TABLE ACCOUNT_ANALYTICS (
    ACCOUNT_ID BIGINT NOT NULL PRIMARY KEY,
    ANALYTICS_USER_ID VARCHAR(100),
    OPTED_OUT_AT DATETIME(6),
    GA_CLIENT_IDS TEXT NOT NULL,
    GA4_DELETION_STATUS VARCHAR(20) NOT NULL DEFAULT 'NOT_REQUESTED',
    AMPLITUDE_DELETION_STATUS VARCHAR(20) NOT NULL DEFAULT 'NOT_REQUESTED',
    AMPLITUDE_DELETION_IDS TEXT,
    AMPLITUDE_DELETION_REQUESTED_AT DATETIME(6),
    CREATED_AT DATETIME(6) NOT NULL,
    UPDATED_AT DATETIME(6) NOT NULL
);
