/**
 * 번호 주석 스펙 — prototype-agent 스킬의 PRD 규칙(§1.4)을 화면 위에서 그대로 쓴다.
 *
 * 규칙 요약:
 * - 번호는 **화면 위 요소 위치 기준**으로 준다. 큰 영역이 `1`, 그 안의 요소가 `1-1`·`1-2`
 * - 본 화면의 시각 요소는 빠짐없이 어느 번호의 표시 또는 데이터에 설명이 있어야 한다 (미설명 0)
 * - 배지를 붙인 뒤 **번호 → 대상 요소의 실제 텍스트**로 되돌려 대조한다
 *
 * 마지막 규칙이 정적 캡처에서는 손으로 하는 일이었다. 여기서는 살아있는 DOM 을 읽으므로
 * 패널이 대조표를 자동으로 만든다 — 배지가 엉뚱한 요소에 붙으면 바로 드러난다.
 */

export type AnnoEntry = {
  /** `1` · `1-1` · `1-2`. 화면 위 위치 기준. */
  n: string;
  /** 요소 이름 — 패널 소제목. */
  title: string;
  /**
   * `data-anno` 를 달 수 없는 요소를 CSS 선택자로 가리킨다.
   *
   * 공용 패키지(`@studyclub/ui`)의 컴포넌트는 프로토 사정으로 고치지 않는다 —
   * 팀이 같이 쓰는 코드에 프로토 전용 속성을 심으면 그게 실서비스로 흘러간다.
   * 모달 전체처럼 그런 요소만 여기로 가리킨다. 되도록 `data-anno` 를 쓸 것.
   */
  selector?: string;
  /** 표시 — 무엇이 보이는가. */
  display?: string[];
  /** 동작 — 누르면/입력하면 무엇이 일어나는가. */
  behavior?: string[];
  /** 정책 — 판정 기준·제약. */
  policy?: string[];
  /** 데이터 — 어떤 값이 어디서 오는가. */
  data?: string[];
  /**
   * 이 요소가 **조건부**로만 그려질 때의 조건 (탭 전환·상태 분기 등).
   * 적어 두면 지금 화면에 없어도 "대조 실패"로 세지 않는다 —
   * 조건부 요소까지 실패로 뜨면 경고가 늘 켜져 있어 진짜 실패를 못 본다.
   */
  when?: string;
  /** 배지 위치를 기본값(top -10, left -10)에서 추가로 이동할 픽셀. 겹침 보정에 사용. */
  chipOffset?: { top?: number; left?: number };
};

export type ScreenSpec = {
  /** 화면 이름 — 패널 제목. */
  screen: string;
  /**
   * Story ID. `stories.md` 발번 대장에서 **실제로 발급받은** 번호만 적는다.
   * 없으면 비워 둔다 — 그럴듯한 `ST-012` 를 적으면 읽는 사람은 원장이 있다고 믿는다.
   */
  story?: string;
  /**
   * 스토리 칩에 적을 짧은 이름.
   *
   * 한 화면에 여러 Story 가 산다. 스터디 상세만 해도 신청자 승인·출석·수정이 한 지면에 있고,
   * 번호는 **Story 마다 따로** 매겨진다. 칩으로 Story 를 고르면 그 Story 번호만 화면에 뜬다.
   * ID 발급 전에는 이 요약이 칩 이름이 된다 (`story` 가 있으면 그쪽이 우선).
   */
  chip?: string;
  /**
   * 이 Story 의 번호 이름공간. 요소는 `data-anno="<scope>:<n>"` 으로 단다.
   *
   * **번호는 Story 마다 1 부터 다시 매긴다.** 한 지면에 Story 가 여럿이라고 번호를 이어 붙이면
   * (수정 Story 가 9 부터 시작하는 식) 문서를 읽는 사람은 앞 번호를 찾아 헤맨다.
   * 한 요소가 여러 Story 에 나오면 공백으로 나열한다 — `data-anno="attendee:2 crew:1"`.
   */
  scope?: string;
  /** 이 화면이 하지 않는 것 · 오픈 이슈. */
  notes?: string[];
  entries: AnnoEntry[];
};
