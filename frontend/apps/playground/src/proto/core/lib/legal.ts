/**
 * 이용약관·개인정보처리방침 본문.
 *
 * 원문이 표·목록·인용을 섞어 쓰므로 문단 배열로는 담기지 않는다. 블록 단위로 모델링했다.
 * 마크다운 렌더러를 붙이지 않은 이유 — 프로토 하나 때문에 팀 의존성을 늘리지 않는다.
 *
 * 원문의 「⚠️ 작성 안내」는 옮기지 않았다. 문서를 쓰는 사람에게 주는 지시지 이용자에게 고지하는
 * 내용이 아니라, 프로토에 두면 유저가 볼 화면이 아닌 것이 시안에 섞인다. 그 내용은 원문에 남아 있다.
 */

/** 영문 문안이 아직 없다. 법률 문서는 임의로 번역하지 않는다 — `en` 은 있을 때만 채운다. */
export type Text = { ko: string; en?: string };

export type Block =
  /** `strong` 은 원문에서 굵게 강조된 문단. 면책·책임 한계처럼 눈에 걸려야 하는 조항이다. */
  | { kind: 'p'; text: Text; strong?: boolean }
  | { kind: 'ul'; items: Text[] }
  /** `sub` 는 상위 항에 딸린 각 호 목록. 들여쓰지 않으면 항 번호와 호 번호가 같은 줄에서 섞여 읽힌다. */
  | { kind: 'ol'; items: Text[]; sub?: boolean }
  /** 번호 + 굵은 제목 + 설명 */
  | { kind: 'steps'; items: { title: Text; body: Text }[] }
  | { kind: 'table'; head: Text[]; rows: Text[][] }
  /** 본문의 일부인 강조 인용 */
  | { kind: 'note'; text: Text };

export type LegalSection = {
  /** 목차와 본문을 잇는 앵커. URL 해시로도 쓴다. */
  id: string;
  /** 이 조가 속한 장(章). 값이 바뀌는 지점에서만 장 제목을 그린다. */
  chapter?: Text;
  heading: Text;
  blocks?: Block[];
};

export type LegalDocument = {
  title: Text;
  /** 문서 맨 위 도입부 — 조항 번호가 붙지 않는 부분. */
  intro?: Block[];
  /** 최종 개정일 (YYYY-MM-DD). */
  updatedAt: string;
  /** 초안 표시. 확정되면 지운다. */
  draft?: boolean;
  /** 영문 문안 보유 여부. 없으면 en 로케일에서 안내를 띄운다. */
  translated?: boolean;
  sections: LegalSection[];
};

const p = (ko: string): Block => ({ kind: 'p', text: { ko } });
const b = (ko: string): Block => ({ kind: 'p', text: { ko }, strong: true });
const ul = (...items: string[]): Block => ({ kind: 'ul', items: items.map((ko) => ({ ko })) });
const ol = (...items: string[]): Block => ({ kind: 'ol', items: items.map((ko) => ({ ko })) });
/** 각 호 — 상위 항에 딸린 목록 */
const sol = (...items: string[]): Block => ({ kind: 'ol', sub: true, items: items.map((ko) => ({ ko })) });
const note = (ko: string): Block => ({ kind: 'note', text: { ko } });
const steps = (...items: [string, string][]): Block => ({
  kind: 'steps',
  items: items.map(([title, body]) => ({ title: { ko: title }, body: { ko: body } })),
});
const table = (head: string[], rows: string[][]): Block => ({
  kind: 'table',
  head: head.map((ko) => ({ ko })),
  rows: rows.map((r) => r.map((ko) => ({ ko }))),
});

